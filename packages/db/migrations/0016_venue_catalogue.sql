-- Several venues on one till account (brief CF-16, D73, T71). Expand only: two nullable columns on
-- the table that links a till venue to ours, and their backfill; nothing existing is renamed,
-- dropped or rewritten.
--   catalogue_id  the catalogue (item set) the till venue sells from (`Barsys_getlist.menu_id`);
--                 venues can share one. The worker writes it whenever it reads the venue list.
--   price_source  which till price the venue's menu shows: per venue now (D73), so far one
--                 setting of the integration (`config.price_source`).
--
-- The columns and checks are generated by drizzle-kit from src/schema.ts; the backfill and the
-- statements around it are written by hand. One transaction (the migrator runs pending
-- migrations in one), in this order:
--   0. the three tables the backfill reads or writes stop forcing row-level security on their
--      owner, and the link table stops touching `updated_at`: on a database whose owner does not
--      bypass RLS (Supabase's `postgres`) the owner would otherwise see no row, and the backfill
--      should leave every other column as it was. Both come back at the end; ALTER TABLE holds
--      an ACCESS EXCLUSIVE lock until commit, so nobody else sees the tables meanwhile;
--   1. the columns and their checks (generated);
--   2. price_source from the integration's `config.price_source` (`current_price`, else the
--      default `actual_price`, as the worker read it); catalogue_id from the newest stored
--      `Barsys_getlist` record of the venue, when there is one (the next full pull reads the
--      list again and corrects it);
--   3. post-check: refuse if a row is left without a price source (the owner could not see the
--      rows);
--   4. back to normal.

-- 0. Owner access for the backfill; undone at step 4.
ALTER TABLE "restro"."barsy_venues" NO FORCE ROW LEVEL SECURITY;--> statement-breakpoint
ALTER TABLE "restro"."integrations" NO FORCE ROW LEVEL SECURITY;--> statement-breakpoint
ALTER TABLE "restro"."source_records" NO FORCE ROW LEVEL SECURITY;--> statement-breakpoint
ALTER TABLE "restro"."barsy_venues" DISABLE TRIGGER "barsy_venues_touch_updated_at";--> statement-breakpoint

-- 1. The columns and their checks.
ALTER TABLE "restro"."barsy_venues" ADD COLUMN "catalogue_id" integer;--> statement-breakpoint
ALTER TABLE "restro"."barsy_venues" ADD COLUMN "price_source" text;--> statement-breakpoint
ALTER TABLE "restro"."barsy_venues" ADD CONSTRAINT "till_venue_price_source" CHECK ("restro"."barsy_venues"."price_source" is null or "restro"."barsy_venues"."price_source" in ('actual_price', 'current_price'));--> statement-breakpoint
ALTER TABLE "restro"."barsy_venues" ADD CONSTRAINT "till_venue_catalogue_id" CHECK ("restro"."barsy_venues"."catalogue_id" is null or "restro"."barsy_venues"."catalogue_id" >= 0);--> statement-breakpoint

-- 2. Backfill.
UPDATE "restro"."barsy_venues" AS venue
SET "price_source" = CASE
  WHEN integration."config" ->> 'price_source' = 'current_price' THEN 'current_price'
  ELSE 'actual_price'
END
FROM "restro"."integrations" AS integration
WHERE integration."id" = venue."integration_id";--> statement-breakpoint
UPDATE "restro"."barsy_venues" AS venue
SET "catalogue_id" = (
  SELECT (record."payload" ->> 'menu_id')::integer
  FROM "restro"."source_records" AS record
  WHERE record."integration_id" = venue."integration_id"
    AND record."external_type" = 'barsy_venue'
    AND record."external_id" = venue."bid"::text
    AND (record."payload" ->> 'menu_id') ~ '^[0-9]{1,9}$'
  ORDER BY record."fetched_at" DESC, record."id" DESC
  LIMIT 1
);--> statement-breakpoint

-- 3. Post-check.
DO $$
DECLARE
  without_price bigint;
BEGIN
  SELECT count(*) INTO without_price FROM "restro"."barsy_venues" WHERE "price_source" IS NULL;
  IF without_price > 0 THEN
    RAISE EXCEPTION '0016_venue_catalogue: % venue links are still without a price source; the migration owner must be able to read restro.integrations and update the link table (superuser, BYPASSRLS, or the table owner)', without_price;
  END IF;
END
$$;--> statement-breakpoint

-- 4. Back to normal.
ALTER TABLE "restro"."barsy_venues" ENABLE TRIGGER "barsy_venues_touch_updated_at";--> statement-breakpoint
ALTER TABLE "restro"."source_records" FORCE ROW LEVEL SECURITY;--> statement-breakpoint
ALTER TABLE "restro"."integrations" FORCE ROW LEVEL SECURITY;--> statement-breakpoint
ALTER TABLE "restro"."barsy_venues" FORCE ROW LEVEL SECURITY;
